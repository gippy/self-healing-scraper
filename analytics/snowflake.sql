-- Snowflake: the scrapers write every poll to SCRAPED_ITEMS (one row per lot per scrape).
-- LOT_PRICES turns that stream into one live row per lot, refreshed every minute: the first price seen,
-- the latest price, and how fast it grew.
CREATE OR REPLACE DYNAMIC TABLE LOT_PRICES
  TARGET_LAG = '1 minute'
  WAREHOUSE = SCRAPER_WH
AS
SELECT
  SCRAPER,
  ITEM_ID,
  MAX_BY(TITLE, SCRAPED_AT) AS TITLE,
  MAX_BY(CATEGORY, SCRAPED_AT) AS CATEGORY,
  MAX_BY(CURRENCY, SCRAPED_AT) AS CURRENCY,
  MIN_BY(AMOUNT, SCRAPED_AT) AS FIRST_PRICE,
  MAX_BY(AMOUNT, SCRAPED_AT) AS LATEST_PRICE,
  MAX(BIDS) AS BIDS,
  ROUND(100 * (MAX_BY(AMOUNT, SCRAPED_AT) / NULLIF(MIN_BY(AMOUNT, SCRAPED_AT), 0) - 1), 1) AS GROWTH_PCT,
  ROUND((MAX_BY(AMOUNT, SCRAPED_AT) - MIN_BY(AMOUNT, SCRAPED_AT))
    / GREATEST(DATEDIFF('second', MIN(SCRAPED_AT), MAX(SCRAPED_AT)) / 60, 1), 2) AS USD_PER_MIN,
  MIN(SCRAPED_AT) AS FIRST_SEEN,
  MAX(SCRAPED_AT) AS LAST_SEEN,
  COUNT(*) AS SCRAPES
FROM SCRAPED_ITEMS
GROUP BY SCRAPER, ITEM_ID;

-- A lot no longer seen for two minutes, compared with the newest scrape, has sold or closed.
CREATE OR REPLACE VIEW LOT_PRICE_BOARD AS
SELECT *,
  IFF(LAST_SEEN < DATEADD('minute', -2, (SELECT MAX(LAST_SEEN) FROM LOT_PRICES)), 'sold or closed', 'live') AS STATE
FROM LOT_PRICES;

-- The fastest-rising lots.
SELECT ITEM_ID, TITLE, FIRST_PRICE, LATEST_PRICE, GROWTH_PCT, USD_PER_MIN, STATE
FROM LOT_PRICE_BOARD
WHERE SCRAPES > 2
ORDER BY GROWTH_PCT DESC
LIMIT 10;
